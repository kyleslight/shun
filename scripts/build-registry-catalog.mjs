#!/usr/bin/env node
/**
 * Build the registry catalog from the packages in `registry/seeds/`.
 *
 *   node --experimental-strip-types scripts/build-registry-catalog.mjs
 *   node --experimental-strip-types scripts/build-registry-catalog.mjs --upload --local
 *   node --experimental-strip-types scripts/build-registry-catalog.mjs --upload
 *
 * `--upload --local` writes into wrangler's local R2 for `pnpm registry:dev`;
 * `--upload` targets the deployed bucket and therefore needs an explicit go-ahead.
 * The generation itself lives in `registry/src/build-catalog.ts`, so the tests
 * exercise the same code the release does.
 */
import { execFileSync } from 'node:child_process'
import { glob, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildMarketplaceCatalog } from '../registry/src/build-catalog.ts'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const seedsRoot = join(root, 'registry', 'seeds')
const distRoot = join(root, 'registry', 'dist')
const bucket = 'shun-marketplace'
const args = new Set(process.argv.slice(2))
const upload = args.has('--upload')
const local = args.has('--local')

await rm(distRoot, { recursive: true, force: true })
/**
 * Ids the application itself owns. A bundled package ships inside Shun, so the
 * registry refuses to publish under its id; the list is generated from the
 * repository rather than maintained by hand, and a test fails if it drifts.
 */
async function reservedIds() {
  const ids = new Map()
  for await (const path of glob(join(root, 'resources', 'plugins', '*', 'manifest.json'))) {
    ids.set(JSON.parse(await readFile(path, 'utf8')).id, 'bundled with Shun')
  }
  const plugins = await readFile(join(root, 'src', 'main', 'plugins.ts'), 'utf8')
  for (const match of plugins.matchAll(/\n    id: '([a-z0-9.-]+)',\n/g)) {
    if (!ids.has(match[1])) ids.set(match[1], 'a first-party connector shipped with Shun')
  }
  return ids
}

const reserved = await reservedIds()
const reservedSql = ['-- Generated by scripts/build-registry-catalog.mjs from the application repository.',
  '-- A bundled id ships inside Shun, so the registry refuses to publish under it.',
  'DELETE FROM reserved_ids;',
  ...[...reserved].sort(([left], [right]) => left < right ? -1 : 1).map(([id, note]) => `INSERT OR REPLACE INTO reserved_ids (id, owner, note) VALUES ('${id}', 'first-party', '${note}');`)].join('\n') + '\n'
await writeFile(join(root, 'registry', 'reserved-ids.sql'), reservedSql)
await mkdir(join(root, 'registry', 'dist'), { recursive: true })
await writeFile(join(root, 'registry', 'dist', 'reserved-ids.sql'), reservedSql)
console.log(`reserved ids: ${reserved.size} -> registry/reserved-ids.sql`)

const curation = JSON.parse(await readFile(join(root, 'registry', 'catalog.config.json'), 'utf8'))
const { catalog, objects } = await buildMarketplaceCatalog({ seedsRoot, featured: curation.featured })

for (const object of objects) {
  const file = join(distRoot, object.key)
  await mkdir(dirname(file), { recursive: true })
  await writeFile(file, object.bytes)
}
for (const entry of catalog.entries) {
  const version = entry.versions[0]
  console.log(`packed ${entry.id}@${version.version}  archive ${version.archiveBytes} B  files ${version.files}  sha256 ${version.sha256.slice(0, 12)}…  content ${version.contentSha256.slice(0, 12)}…`)
}
// A seed plugin is first-party: it goes straight into the catalog, with the
// curation order the registry owns.
const seedSql = [
  '-- Generated by scripts/build-registry-catalog.mjs from registry/seeds.',
  ...catalog.entries.flatMap((entry) => {
    const version = entry.versions[0]
    const quote = (value) => value === undefined || value === null ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`
    return [
      `INSERT INTO plugins (id, name, description, publisher, icon, keywords, license, homepage, repository, permissions, latest, featured, updated_at, status) VALUES (${quote(entry.id)}, ${quote(entry.name)}, ${quote(entry.description)}, ${quote(entry.publisher)}, ${quote(entry.icon)}, ${quote(entry.keywords ? JSON.stringify(entry.keywords) : undefined)}, ${quote(entry.license)}, ${quote(entry.homepage)}, ${quote(entry.repository)}, ${quote(JSON.stringify(entry.permissions))}, ${quote(entry.latest)}, ${entry.featured ?? 'NULL'}, ${quote(entry.updatedAt)}, 'published') ON CONFLICT(id) DO UPDATE SET latest = excluded.latest, updated_at = excluded.updated_at, featured = COALESCE(excluded.featured, plugins.featured);`,
      `INSERT INTO plugin_versions (plugin_id, version, published_at, engines, archive_sha256, content_sha256, files, bytes, archive_bytes, changelog, yanked_at) VALUES (${quote(entry.id)}, ${quote(version.version)}, ${quote(version.publishedAt)}, ${quote(version.engines ? JSON.stringify(version.engines) : undefined)}, ${quote(version.sha256)}, ${quote(version.contentSha256)}, ${version.files}, ${version.bytes}, ${version.archiveBytes}, NULL, NULL);`,
    ]
  }),
].join('\n') + '\n'
await writeFile(join(distRoot, 'bootstrap.sql'), `${reservedSql}${seedSql}`)
console.log(`catalog: ${catalog.entries.length} entr${catalog.entries.length === 1 ? 'y' : 'ies'} -> registry/dist (bootstrap.sql, reserved-ids.sql)`)

if (!upload) {
  console.log('\nno upload requested. To publish these bytes:')
  console.log('  pnpm registry:catalog --upload --local   # wrangler local R2, for pnpm registry:dev')
  console.log('  pnpm registry:catalog --upload           # the deployed bucket')
  console.log('  npx wrangler d1 execute shun-marketplace --remote --file registry/dist/bootstrap.sql')
} else {
  console.log(`\nuploading to ${bucket}${local ? ' (local)' : ''} …`)
  for (const object of objects) {
    execFileSync('wrangler', ['r2', 'object', 'put', `${bucket}/${object.key}`, '--file', join(distRoot, object.key), ...(local ? ['--local'] : ['--remote'])], { cwd: join(root, 'registry'), stdio: 'inherit' })
  }
  console.log(`uploaded ${objects.length} objects`)
}
